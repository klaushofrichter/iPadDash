#!/bin/sh
# Build iPadDash and install it on the iPads (iOS 12), over USB or Wi-Fi.
#
# Xcode 27 refuses deployment targets below iOS 15, so the project validates
# against 15.0 while the compiler and linker target iOS 12 (see
# IPAD_REAL_DEPLOYMENT_TARGET in the target's build settings). Xcode still writes
# MinimumOSVersion=15.0 into Info.plist, so this script patches it, re-signs the
# bundle, and installs it with libimobiledevice (Xcode 27 can't deploy to iOS 12).
#
# Usage:
#   ./deploy.sh [IPAD]     build, patch, sign, install, launch
#   ./deploy.sh --check    unsigned build + checks only (no iPad or Apple ID needed)
# IPAD is silver, black, all or a UDID prefix (see ipad-select.sh); it may be
# left out when only one iPad is connected.
#
# Requires: the credentials below in .env; for install also an Apple ID added in
# Xcode, DEVELOPMENT_TEAM set on the target, and `brew install ideviceinstaller`.
set -eu

cd "$(dirname "$0")"
. ./ipad-select.sh
CHECK=""; IPAD=""
for arg in "$@"; do
    case $arg in --check) CHECK=1 ;; *) IPAD=$arg ;; esac
done
[ -n "$CHECK" ] || udids=$(select_ipads "$IPAD")
MIN_OS=12.0
CONFIG=${CONFIG:-Release}
DERIVED=build
APP="$DERIVED/Build/Products/$CONFIG-iphoneos/iPadDash.app"

# Credentials live in .env: STEPS_ACCESS_TOKEN for steps-service, and
# GRAFANA_PROM_USER / GRAFANA_PROM_TOKEN (read-only metrics) for the cluster page,
# UPTIMEROBOT_API_KEY (read-only) for the uptime page, GITHUB_PAT (fine-grained,
# Pull requests: read-only) for the GitHub page.
# The app reads them from the bundled Secrets.plist. Both files are git-ignored.
if [ -f .env ]; then
    env_value() { sed -n "s/^$1=//p" .env | tr -d '"'"'"' \r'; }
    STEPS_ACCESS_TOKEN=$(env_value STEPS_ACCESS_TOKEN)
    GRAFANA_PROM_USER=$(env_value GRAFANA_PROM_USER)
    GRAFANA_PROM_TOKEN=$(env_value GRAFANA_PROM_TOKEN)
    UPTIMEROBOT_API_KEY=$(env_value UPTIMEROBOT_API_KEY)
    GITHUB_PAT=$(env_value GITHUB_PAT)
fi
cat > iPadDash/Secrets.plist <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<!-- Generated by deploy.sh from .env. Do not edit or commit. -->
	<key>StepsToken</key>
	<string>${STEPS_ACCESS_TOKEN:-}</string>
	<key>GrafanaUser</key>
	<string>${GRAFANA_PROM_USER:-}</string>
	<key>GrafanaToken</key>
	<string>${GRAFANA_PROM_TOKEN:-}</string>
	<key>UptimeRobotKey</key>
	<string>${UPTIMEROBOT_API_KEY:-}</string>
	<key>GitHubToken</key>
	<string>${GITHUB_PAT:-}</string>
</dict>
</plist>
EOF

SIGNING=-allowProvisioningUpdates
[ -n "$CHECK" ] && SIGNING=CODE_SIGNING_ALLOWED=NO
xcodebuild -project iPadDash.xcodeproj -scheme iPadDash -configuration "$CONFIG" \
    -destination 'generic/platform=iOS' -derivedDataPath "$DERIVED" "$SIGNING" -quiet build

/usr/libexec/PlistBuddy -c "Set :MinimumOSVersion $MIN_OS" "$APP/Info.plist"

# Fail early if anything slipped in that iOS 12 can't load.
minos=$(otool -l "$APP/iPadDash" | awk '/LC_BUILD_VERSION/{f=1} f&&/minos/{print $2; exit}')
[ "$minos" = "$MIN_OS" ] || { echo "error: binary minos is $minos, expected $MIN_OS" >&2; exit 1; }
modern=$(otool -L "$APP/iPadDash" | grep -E 'SwiftUI|Combine|_Concurrency' || true)
if printf '%s' "$modern" | grep -vq '(.*weak)'; then
    echo "error: binary hard-links a framework that doesn't exist on iOS 12:" >&2
    echo "$modern" >&2
    exit 1
fi
echo "Checks passed: minos $minos, MinimumOSVersion $MIN_OS"
[ -n "$CHECK" ] && exit 0

# Same scheme as the cluster's services: YYYY.MM.DD.N, set at deploy time and not
# stored in the source (other builds say "dev"). N is the same-day count of earlier
# releases, and the local v* git tags are the state. Dated in the cluster's zone.
today=$(TZ=America/Chicago date +%Y.%m.%d)
tags=$(git tag -l "v$today.*")
VERSION="$today.$(( $(printf '%s' "$tags" | grep -c '^' || true) + 1 ))"
/usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Info.plist"

# Patching Info.plist invalidated the signature; re-sign with the same identity
# and entitlements Xcode used.
identity=$(codesign -dvv "$APP" 2>&1 | sed -n 's/^Authority=\(Apple Development.*\)$/\1/p' | head -1)
codesign -d --entitlements :- "$APP" > "$DERIVED/entitlements.plist" 2>/dev/null
codesign -f -s "$identity" --entitlements "$DERIVED/entitlements.plist" "$APP"

rm -rf "$DERIVED/ipa" && mkdir -p "$DERIVED/ipa/Payload"
cp -R "$APP" "$DERIVED/ipa/Payload/"
(cd "$DERIVED/ipa" && zip -qr ../iPadDash.ipa Payload)
bundle_id=$(/usr/libexec/PlistBuddy -c "Print :CFBundleIdentifier" "$APP/Info.plist")
DDI_DIR=${DDI_DIR:-$HOME/Library/Developer/iPadDash-DDI/12.4}
for udid in $udids; do
    link=$(ipad_link "$udid")
    name="$(ipad_color "$udid") iPad"
    ideviceinstaller $link -u "$udid" install "$DERIVED/iPadDash.ipa"
    git rev-parse -q --verify "refs/tags/v$VERSION" >/dev/null || git tag "v$VERSION"
    echo "Installed version $VERSION on the $name${link:+ over Wi-Fi}"

    # Launch it. debugserver needs the iOS 12 developer disk image, which Xcode 27
    # no longer ships: 12.4.zip from github.com/filsv/iOSDeviceSupport, unpacked
    # into $DDI_DIR (the iPad checks Apple's signature when mounting). The image
    # stays mounted until the iPad reboots.
    if ! ideviceimagemounter $link -u "$udid" list 2>/dev/null | grep -q ImageSignature; then
        if [ ! -f "$DDI_DIR/DeveloperDiskImage.dmg" ]; then
            echo "Not launched: no developer disk image in $DDI_DIR"
            continue
        fi
        ideviceimagemounter $link -u "$udid" mount "$DDI_DIR/DeveloperDiskImage.dmg" \
            "$DDI_DIR/DeveloperDiskImage.dmg.signature" >/dev/null
    fi
    idevicedebug $link -u "$udid" --detach run "$bundle_id" && echo "Launched on the $name"
done
